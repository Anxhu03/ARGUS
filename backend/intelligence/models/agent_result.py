"""
Data models for specialist agent execution outcomes.
"""

from enum import Enum
from typing import Any, Dict, Optional
from pydantic import BaseModel, Field


class AgentStatus(str, Enum):
    """
    Execution status of an individual specialist agent.
    """
    SUCCESS = "success"
    PARTIAL = "partial"
    FAILED = "failed"
    ESCALATED = "escalated"


class AgentResult(BaseModel):
    """
    Uniform result structure returned by any ARGUS agent (Billing, Order, Tech, Coordinator).
    """
    agent_name: str = Field(
        ...,
        description="Name of the agent that produced this result."
    )
    status: AgentStatus = Field(
        ...,
        description="Execution status."
    )
    output: Dict[str, Any] = Field(
        default_factory=dict,
        description="Structured findings, actions, or recommendations generated by the agent."
    )
    confidence: float = Field(
        ...,
        ge=0.0,
        le=1.0,
        description="Confidence score in the agent's findings."
    )
    notes: Optional[str] = Field(
        default=None,
        description="Diagnostic notes or reasoning commentary."
    )
    execution_time_ms: Optional[float] = Field(
        default=None,
        description="Time taken to execute in milliseconds."
    )

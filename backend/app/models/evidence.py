from enum import Enum
from typing import Any, Dict, List, Optional
from pydantic import BaseModel, Field

class EvidenceSourceLabel(str, Enum):
    VERIFIED = "verified"     # Cryptographic / authentic upstream enterprise record
    SIMULATED = "simulated"   # Synthetic telemetry generated by deterministic local adapter
    MOCK = "mock"             # Static fixture or user test input

class EvidenceStatus(str, Enum):
    VERIFIED = "Verified"
    PENDING = "Pending"
    CONFLICTING = "Conflicting"
    REQUIRES_CLARIFICATION = "Requires Clarification"
    FAILED = "Failed"

class VerificationCheck(BaseModel):
    checkName: str
    passed: bool
    detail: str

class VerificationAudit(BaseModel):
    verifiedAt: str
    passed: bool
    checks: List[VerificationCheck] = Field(default_factory=list)
    reason: str
    confidenceScore: float = 100.0
    confidenceBasis: str = "Deterministic cryptographic verification"

class EvidenceItem(BaseModel):
    id: str
    caseId: Optional[str] = None
    title: str
    type: str = "Telemetry Data"
    source: str = "System Gateway"
    sourceLabel: EvidenceSourceLabel = EvidenceSourceLabel.SIMULATED
    timestamp: str
    status: EvidenceStatus = EvidenceStatus.PENDING
    description: str = ""
    payload: Dict[str, Any] = Field(default_factory=dict)
    sha256: Optional[str] = None
    filePreviewUrl: Optional[str] = None
    confidenceScore: float = 95.0
    confidenceBasis: Optional[str] = None
    findings: List[str] = Field(default_factory=list)
    relatedEvidenceIds: List[str] = Field(default_factory=list)
    verificationAudit: Optional[VerificationAudit] = None

class EvidenceCreate(BaseModel):
    title: str = Field(..., min_length=3, description="Descriptive title of the evidence artifact")
    type: str = Field(..., min_length=2, description="Evidence category (e.g. Financial Record, Carrier Telemetry, Hardware Sensor Record, Database Entity, Customer Upload)")
    source: str = Field(..., min_length=2, description="Source adapter name (e.g. Stripe API, FastTrack Carrier API, Warehouse Laser Scale, OMS Postgres)")
    sourceLabel: Optional[EvidenceSourceLabel] = EvidenceSourceLabel.SIMULATED
    timestamp: Optional[str] = None
    description: str = Field("", description="Observed value summary or technical observation")
    payload: Optional[Dict[str, Any]] = Field(default_factory=dict)
    sha256: Optional[str] = None
    filePreviewUrl: Optional[str] = None
    relatedEvidenceIds: Optional[List[str]] = Field(default_factory=list)

class ContradictionModel(BaseModel):
    headline: str
    disclaimer: str = "Notice: Contradiction does NOT imply customer fraud. Telemetry discrepancies and third-party logistics errors are evaluated objectively."
    customerClaim: str
    systemEvidence: str
    conflictFields: List[str]
    evidenceSources: List[str]
    conflictingEvidenceIds: List[str] = Field(default_factory=list)
    analysis: str
    recommendedStep: str
    detectedAt: Optional[str] = None

class RootCauseChainLink(BaseModel):
    label: str  # "Evidence" | "Finding" | "Root Cause"
    text: str
    evidenceId: Optional[str] = None

class RootCauseModel(BaseModel):
    headline: str
    summary: str
    chain: List[RootCauseChainLink] = Field(default_factory=list)
    impact: str = "Operational impact documented"
    verifiedFacts: List[str] = Field(default_factory=list)
    suspectedCauses: List[str] = Field(default_factory=list)
    unresolvedQuestions: List[str] = Field(default_factory=list)
    uncertaintyLevel: str = "Low"  # "Low" | "Moderate" | "High"
    isSufficient: bool = True
    nextAction: Optional[str] = None
    sourceLabel: str = "simulated-deterministic-engine"

class VerificationReportModel(BaseModel):
    caseId: str
    status: str  # "verified" | "conflicts_detected" | "evidence_required" | "pending"
    totalEvidence: int
    verifiedCount: int
    conflictingCount: int
    pendingCount: int
    discrepancies: List[str] = Field(default_factory=list)
    missingInformation: List[str] = Field(default_factory=list)
    crossSourceChecks: List[Dict[str, Any]] = Field(default_factory=list)
    evidence: List[EvidenceItem] = Field(default_factory=list)
    contradiction: Optional[ContradictionModel] = None
    rootCause: Optional[RootCauseModel] = None
    generatedAt: str
